import { createRequire } from 'node:module';
import { resolve, join } from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(join(resolve(process.env.PLAYWRIGHT_MODULE_DIR || 'node_modules'), '_test.cjs'));
const { chromium } = require('playwright');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const base = process.env.LANGUAGES_TEST_URL || 'http://127.0.0.1:8016';
try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 950 } });
    const errors = [];
    page.on('pageerror', (e) => errors.push(e.message));
    await page.goto(base + '/login');
    await page.locator('#email').fill('language-test@example.test');
    await page.locator('#password').fill('LanguageTest!123');
    await Promise.all([page.waitForURL('**/dashboard'), page.locator('button[type=submit]').click()]);
    await page.goto(base + '/dashboard/languages');
    await page.locator('#languages-panel').waitFor();
    assert.equal(await page.locator('aside a[href$="/dashboard/languages"]').isVisible(), true);
    const rows = await page.locator('tr[data-language]').evaluateAll((rows) => rows.map((row) => ({ id: row.dataset.language, code: row.querySelector('bdi').textContent })));
    assert.deepEqual(rows.map((row) => row.code), ['ar', 'en', 'fr']);
    const id = (code) => rows.find((row) => row.code === code).id;
    const toggle = (code, field) => page.locator('#' + field + '-' + id(code));
    const change = async (code, field) => {
        await toggle(code, field).click();
        await page.waitForFunction(() => document.querySelector('#languages-panel').getAttribute('aria-busy') === 'false');
    };
    assert.equal(await toggle('en', 'default').isChecked(), true);
    await change('fr', 'active');
    assert.equal(await toggle('fr', 'active').isChecked(), false);
    assert.match(await page.locator('#languages-message').textContent(), /not ready/);
    await change('ar', 'default');
    assert.equal(await toggle('ar', 'default').isChecked(), true);
    assert.equal(await toggle('en', 'default').isChecked(), false);
    await change('ar', 'active');
    assert.equal(await toggle('ar', 'active').isChecked(), true);
    await change('en', 'active');
    assert.equal(await toggle('en', 'active').isChecked(), false);
    assert.equal(page.url(), base + '/dashboard/languages');
    assert.equal(await page.locator('[data-language-switcher] [data-locale="en"]').count(), 0);
    await page.reload();
    assert.equal(await page.locator('html').getAttribute('lang'), 'ar');
    assert.equal(await page.locator('html').getAttribute('dir'), 'rtl');
    await page.getByRole('button', { name: 'اللغة', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: 'English', exact: true }).count(), 0);
    assert.equal(await page.getByRole('button', { name: 'Français', exact: true }).count(), 0);
    await page.getByRole('button', { name: 'اللغة', exact: true }).click();
    await page.screenshot({ path: '.tools/languages-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.locator('button[data-bs-target="#sidebar-menu"]').click();
    await page.locator('#sidebar-menu.show').waitFor();
    assert.equal(await page.locator('aside a[href$="/dashboard/languages"]').isVisible(), true);
    await page.locator('button[data-bs-target="#sidebar-menu"]').click();
    await page.screenshot({ path: '.tools/languages-mobile.png', fullPage: true });
    await change('en', 'active');
    assert.match(await page.locator('#languages-message').textContent(), /تم تحديث/);
    await page.route('**/dashboard/languages/*', (route) => route.abort('failed'));
    await toggle('en', 'active').click();
    await page.waitForFunction(() => document.querySelector('#languages-message').textContent.includes('غير معروفة'));
    assert.equal(await toggle('ar', 'active').isDisabled(), true);
    assert.equal(await toggle('en', 'active').isDisabled(), true);
    assert.deepEqual(errors, []);
    console.log('PASS: login, index order, AJAX success/rejection, default replacement, French readiness, session fallback/switcher, RTL, 390px containment, unknown network result locks, no uncaught JS errors.');
} finally { await browser.close(); }
